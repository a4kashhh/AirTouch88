/*
 * ============================================================================
 * AIRTOUCH-88 | Bitmap & Font Definitions
 * ============================================================================
 *
 * This file contains predefined bitmap patterns used by the AIRTOUCH-88
 * 8x8 LED Matrix Display.
 *
 * ---------------------------------------------------------------------------
 * 8x8 BITMAP FORMAT
 * ---------------------------------------------------------------------------
 *
 * Each bitmap contains 8 bytes.
 *
 *   - 1 = LED ON
 *   - 0 = LED OFF
 *   - Each byte represents one row.
 *   - Each bit represents one column.
 *
 * Example:
 *
 *   0b00111100
 *
 *   ..####..
 *
 * ---------------------------------------------------------------------------
 * 5x7 FONT FORMAT
 * ---------------------------------------------------------------------------
 *
 * Characters use a 5-column × 7-row format.
 *
 *   - Only the lower 5 bits of each byte are used.
 *   - 1 = LED ON
 *   - 0 = LED OFF
 *
 * Example:
 *
 *   0b10101
 *
 *   #.#.#
 *
 * These characters can be combined and scrolled across the 8x8 display.
 *
 * ============================================================================
 */


