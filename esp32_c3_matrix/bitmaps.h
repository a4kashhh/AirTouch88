/*
 * ============================================================================
 * AIRTOUCH-88
 * Bitmap and Font Definitions
 * ============================================================================
 *
 * This file contains two different display formats:
 *
 * 1. 8x8 BITMAPS
 *    Used for static single characters, symbols, icons and patterns.
 *
 * 2. 5x7 FONT
 *    Used for dynamic text such as words and sentences.
 *    Characters can be combined and scrolled across the 8x8 LED matrix.
 *
 * ---------------------------------------------------------------------------
 * BIT FORMAT
 * ---------------------------------------------------------------------------
 *
 * 1 = LED ON
 * 0 = LED OFF
 *
 * ============================================================================
 */


